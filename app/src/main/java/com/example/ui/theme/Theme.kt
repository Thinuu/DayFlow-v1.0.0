/**
 * DayFlow application theme.
 *
 * [darkTheme] is driven by the persisted [AppThemeMode] preference:
 *   DARK   → true  (default)
 *   LIGHT  → false
 *   SYSTEM → follows [isSystemInDarkTheme]
 *
 * [dynamicColor] is intentionally false to keep the bespoke DayFlow
 * Elegant Dark palette active instead of Android 12+ wallpaper colours.
 */
@Composable
fun DayFlowTheme(
    darkTheme: Boolean = true, // Default to Elegant Dark theme as requested
    dynamicColor: Boolean = false, // Keep bespoke Elegant Dark theme active
    content: @Composable () -> Unit
) {
    val colorScheme = when {
        dynamicColor && Build.VERSION.SDK_INT >= Build.VERSION_CODES.S -> {
            val context = LocalContext.current
            if (darkTheme) dynamicDarkColorScheme(context) else dynamicLightColorScheme(context)
        }
        darkTheme -> DarkColorScheme
        else -> LightColorScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
